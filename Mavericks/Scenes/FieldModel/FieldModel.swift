enum MapCellType: Int{
    case water = 0
    case earth
    case road
    case rock //
    
    func baseNodeType() -> BaseRaidNodeType{
        switch self {
            case .water:
                    .empty
            case .earth:
                    .field
            case .road:
                    .road
            case .rock:
                    .empty
        }
    }
}

enum MapCellContent: Int{
    case empty = 0
    case base
    case spawn
    case resourceWood
    case resourceStone
    case resourceMetal
    case resourceOil
    case qwestBuild
    case tower
    case block
    case trap
}

struct MapCell {
    let mapCellType   : MapCellType
    let mapCellContent: MapCellContent
}

